<?php

declare(strict_types=1);

use App\Models\Report;
use Illuminate\Support\Facades\Process;
use Illuminate\Testing\TestResponse;

use function Pest\Laravel\assertDatabaseCount;
use function Pest\Laravel\call;

function specialReport(): string
{
    return (string) file_get_contents(__DIR__.'/../../Fixtures/upload-special-chars.md');
}

/**
 * Runs code after sourcing the Mac script, with the arguments as $1, $2.
 *
 * @param  list<string>  $args
 * @param  array<string, string>  $env
 */
function macScript(string $code, array $args = [], array $env = []): string
{
    $result = Process::path(base_path())->env($env)->run(['bash', '-c', 'source scripts/mac-checkup.sh; '.$code, 'bash', ...$args]);

    expect($result->errorOutput())->toBe('');

    return $result->output();
}

function postRawJson(string $body): TestResponse
{
    return call('POST', '/api/reports', [], [], [], ['CONTENT_TYPE' => 'application/json', 'HTTP_ACCEPT' => 'application/json'], $body);
}

describe('the JSON body the Windows script builds', function () {
    // Generated by running New-UploadBody from scripts/windows-checkup.ps1 under Windows PowerShell 5.1
    // on specialReport() with every LF turned into CRLF, so the bytes are what a PC really sends.
    it('is imported once, with quotes, backslashes, unicode and CRLF intact', function () {
        apiUser(['write']);
        $body = (string) file_get_contents(__DIR__.'/../../Fixtures/windows-upload-body.json');

        expect(json_decode($body, true, flags: JSON_THROW_ON_ERROR)['markdown'])
            ->toBe(str_replace("\n", "\r\n", specialReport()));

        postRawJson($body)->assertCreated()->assertJsonPath('created', true);
        postRawJson($body)->assertOk()->assertJsonPath('created', false);

        assertDatabaseCount('reports', 1);
        expect(Report::query()->sole()->markdown)->toBe(specialReport());
    });
});

describe('the JSON body the Mac script builds', function () {
    it('is imported once, with quotes, backslashes, unicode and a missing final newline intact', function () {
        apiUser(['write']);
        $path = tempnam(sys_get_temp_dir(), 'pcc');
        file_put_contents($path, specialReport());

        $body = macScript('pcc_json_body "$1"', [$path]);
        unlink($path);

        expect(json_decode($body, true, flags: JSON_THROW_ON_ERROR))->toBe(['markdown' => specialReport()]);

        postRawJson($body)->assertCreated()->assertJsonPath('created', true);
        postRawJson($body)->assertOk()->assertJsonPath('created', false);

        assertDatabaseCount('reports', 1);
        expect(Report::query()->sole()->markdown)->toBe(specialReport());
    });

    it('escapes control characters and replaces invalid UTF-8', function () {
        $path = tempnam(sys_get_temp_dir(), 'pcc');
        file_put_contents($path, "a\x01b\x1fc\x08\x0c\r\n\xff");

        $body = macScript('pcc_json_body "$1"', [$path]);
        unlink($path);

        expect($body)->toBe('{"markdown":"a\u0001b\u001fc\u0008\u000c\r\n'."\u{fffd}".'"}');
    });
});

describe('the Mac script helpers', function () {
    it('sourcing the script runs no checkup', function () {
        expect(macScript('echo sourced'))->toBe("sourced\n");
    });

    it('accepts https and localhost over http only', function (string $url, bool $accepted) {
        expect(trim(macScript('pcc_valid_url "$1" && echo yes || echo no', [$url])))->toBe($accepted ? 'yes' : 'no');
    })->with([
        'production' => ['https://pc-checkup.thijssensoftware.nl', true],
        'https with path' => ['https://example.test/pc', true],
        'localhost' => ['http://localhost', true],
        'localhost port' => ['http://localhost:8000', true],
        'loopback' => ['http://127.0.0.1:8000/', true],
        'plain http' => ['http://pc-checkup.thijssensoftware.nl', false],
        'localhost lookalike' => ['http://localhost.evil.test', false],
        'userinfo trick' => ['http://localhost:80@evil.test', false],
        'https userinfo' => ['https://localhost@evil.test', false],
        'backslash host' => ['https://good.example\\.evil.test', false],
        'query in host' => ['https://good.example?x', false],
        'ftp' => ['ftp://example.test', false],
        'whitespace' => ['https://example.test/ x', false],
        'empty' => ['', false],
    ]);

    it('takes the token from the option, then the environment, then the token file, trimmed', function () {
        $dir = sys_get_temp_dir().'/pcc-token-'.bin2hex(random_bytes(4));
        mkdir($dir);
        file_put_contents($dir.'/pc-checkup.token', "  1|fromfile  \r\nsecond line\n");

        $find = fn (string $cli, array $env) => trim(macScript(
            'PCC_SCRIPT_DIR="$2"; pcc_find_token "$1"; echo "$PCC_TOKEN_SOURCE:$PCC_TOKEN"', [$cli, $dir], $env,
        ));

        expect($find(" 1|fromoption\n", ['PC_CHECKUP_TOKEN' => '1|fromenv']))->toBe('option:1|fromoption')
            ->and($find('', ['PC_CHECKUP_TOKEN' => " 1|fromenv\n"]))->toBe('environment:1|fromenv')
            ->and($find('', ['PC_CHECKUP_TOKEN' => '  ']))->toBe('file:1|fromfile');

        unlink($dir.'/pc-checkup.token');
        expect($find('', ['PC_CHECKUP_TOKEN' => '']))->toBe(':');
        rmdir($dir);
    });
});
